#!/usr/bin/env node
/*
 * Writes the "request a version for your organisation" templates from src/config.base.json,
 * so the pre-filled defaults can never drift from the app:
 *   .github/ISSUE_TEMPLATE/request-a-version.yml   (GitHub form)
 *   REQUEST-TEMPLATE.md                            (copy-and-email version)
 * Usage: node scripts/make-request-template.js          write files
 *        require("./make-request-template").render()    returns { yml, md } without writing (used by tests)
 */
"use strict";
const fs = require("fs");
const path = require("path");
const ROOT = path.resolve(__dirname, "..");
const base = JSON.parse(fs.readFileSync(path.join(ROOT, "src", "config.base.json"), "utf8"));

const LBW = { jan: "Janmahasatian", boer: "Boer", james: "James", hume: "Hume", peters: "Peters" };
const CENT = { c91: "91st", c98: "98th", c996: "99.6th" };
const yn = (b) => (b ? "yes" : "no");
const plain = (h) => h.replace(/<[^>]*>/g, "");

function sections() {
  const d = base.defaults, t = base.text;
  return [
    {
      id: "org", title: "1. Your organisation",
      help: "Who is this for, and who should we contact?",
      value: "Organisation name: \nContact name: \nContact email: \nApp name (shown in the title bar, e.g. \"Admix - Local Anaesthetic Calculator\"): " + base.org.title + "\nAccent colour (optional, e.g. #0b6bcb): " + base.theme.primary,
    },
    {
      id: "agents", title: "2. Local anaesthetics and maximum doses",
      help: "Edit any line, delete lines you do not want, or add new lines at the bottom. Each line: name | strength in mg per ml (1% = 10 mg/ml) | maximum mg/kg | in use? (yes/no). Prilocaine and chloroprocaine start switched off.",
      value: "Name | mg per ml | max mg/kg | in use?\n" + base.agents.map((a) => `${a.name} | ${a.mgPerMl} | ${a.maxMgPerKg} | ${yn(a.enabled)}`).join("\n"),
    },
    {
      id: "settings", title: "3. Calculation settings",
      help: "Change any value after the colon. Leave a line as it is to keep the default.",
      value: [
        `Lean body weight formula (Janmahasatian, Boer, James, Hume or Peters): ${LBW[d.lbw]}`,
        `Use lean body weight at or above BMI: ${d.bmi}`,
        `Blend gradually from total to lean body weight (yes/no): ${yn(d.blend)}`,
        `Children: lean body weight formula: ${LBW[d.lbwP]}`,
        `Children: obesity threshold (RCPCH BMI centile 91st, 98th or 99.6th): ${CENT[d.pc]}`,
        `Neonatal dose reduction (%, applied when age is 3 months or less): ${d.neoRed}`,
        `Airway lidocaine maximum (mg/kg lean body weight): ${d.lidoCap}`,
        `Airway lidocaine absolute maximum (mg): ${d.lidoMax}`,
        `Co-phenylcaine lidocaine per spray (mg): ${d.cpMg}`,
        `Co-phenylcaine sprays assumed if not stated: ${d.cpN}`,
      ].join("\n"),
    },
    {
      id: "last", title: "4. Lipid emergency (LAST) guideline",
      help: "Which guideline should be shown? (AAGBI 2010 and ASRA 2020 are built in. If your organisation has its own, attach or describe it in section 6.)",
      value: [
        "Guidelines to show (both, AAGBI only, or ASRA only): both",
        `Guideline shown first: ${base.last.default === "asra" ? "ASRA" : "AAGBI"}`,
        `AAGBI bolus (ml/kg): ${d.bolus}`,
        `AAGBI infusion (ml/kg/h): ${d.inf}`,
        `Maximum total lipid (ml/kg): ${d.cap}`,
      ].join("\n"),
    },
    {
      id: "wording", title: "5. Wording shown in the app",
      help: "Edit the sentences to match your local policy.",
      value: [
        `Footer: ${plain(t.footer)}`,
        `Low protein binding line: ${plain(t.proteinBinding)}`,
        `Neonate note: ${plain(t.neonate)}`,
        `Infant note: ${plain(t.infant)}`,
        `Note about the default limits: ${plain(t.defaultLimitsShort)} Verify against local guidance and edit as required.`,
      ].join("\n"),
    },
  ];
}
const FREE = { id: "other", title: "6. Anything else?", help: "Any other request: extra features, other guidelines, different wording, questions. Free text.", value: "" };
const AGREE = "I understand that my organisation's clinical lead must check and sign off these doses and wording before the app is used with patients.";

function render() {
  const S = sections();
  const q = (s) => JSON.stringify(s);
  let yml = "# Generated by scripts/make-request-template.js from src/config.base.json. Do not edit by hand.\n";
  yml += `name: Request a version for your organisation\ndescription: Your own list of local anaesthetics, maximum doses, guideline and wording. The boxes are pre-filled with the current defaults.\ntitle: ${q("Version request: ")}\nlabels: [${q("organisation-request")}]\nbody:\n`;
  yml += `  - type: markdown\n    attributes:\n      value: ${q("Change anything you need. Leave everything else as it is. The boxes already contain the current default values.")}\n`;
  for (const s of S.concat([FREE])) {
    yml += `  - type: textarea\n    id: ${s.id}\n    attributes:\n      label: ${q(s.title)}\n      description: ${q(s.help)}\n`;
    if (s.value) yml += `      value: ${q(s.value)}\n`;
    yml += `    validations:\n      required: ${s.id === "org"}\n`;
  }
  yml += `  - type: checkboxes\n    id: signoff\n    attributes:\n      label: Sign-off\n      options:\n        - label: ${q(AGREE)}\n          required: true\n`;
  let md = "# Request a version of Admix for your organisation\n\nFill this in and email it to Dr George Lui (george.lui@nhs.net). The values below are the current defaults: change what you need and leave the rest.\n\n";
  for (const s of S.concat([FREE])) md += `## ${s.title}\n${s.help}\n\n${s.value}\n\n`;
  md += `## Sign-off\n[ ] ${AGREE}\n`;
  return { yml, md };
}
if (require.main === module) {
  const { yml, md } = render();
  fs.mkdirSync(path.join(ROOT, ".github", "ISSUE_TEMPLATE"), { recursive: true });
  fs.writeFileSync(path.join(ROOT, ".github", "ISSUE_TEMPLATE", "request-a-version.yml"), yml);
  fs.writeFileSync(path.join(ROOT, "REQUEST-TEMPLATE.md"), md);
  console.log("wrote .github/ISSUE_TEMPLATE/request-a-version.yml and REQUEST-TEMPLATE.md");
}
module.exports = { render };
